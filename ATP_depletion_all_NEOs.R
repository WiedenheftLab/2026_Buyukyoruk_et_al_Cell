# ============================================================
# 5. LONG FORMAT + JOIN
# ============================================================

avg_long <- avg %>%
  pivot_longer(
    cols = c(t_0, Glucose, Arabinose),
    names_to = "Condition_raw",
    values_to = "Mean"
  )

sem_long <- sem %>%
  pivot_longer(
    cols = c(t_0, Glucose, Arabinose),
    names_to = "Condition_raw",
    values_to = "SEM"
  )

dat <- avg_long %>%
  left_join(
    sem_long,
    by = c("Sample", "Condition_raw")
  ) %>%
  left_join(
    sample_key,
    by = "Sample"
  ) %>%
  mutate(
    
    # Condition order for facet rows
    Condition = factor(
      Condition_raw,
      levels = c(
        "t_0",
        "Glucose",
        "Arabinose"
      ),
      labels = c(
        "T = 0",
        "T = 30 min (0.2% glucose)",
        "T = 30 min (0.2% arabinose)"
      )
    ),
    
    # Control vs NEO subfacet
    Panel = if_else(
      Label %in% control_order,
      "Controls",
      "NEOs"
    ),
    
    Panel = factor(
      Panel,
      levels = c(
        "Controls",
        "NEOs"
      )
    ),
    
    # Sample order
    Label = factor(
      Label,
      levels = label_order
    )
  )

